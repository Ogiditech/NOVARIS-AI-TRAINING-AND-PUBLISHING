emit('\n-- Demo enrollments, lesson progress and certificates');
const certChars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
learners.forEach(([name]) => {
  const mail = email(name);
  const chosen = [...courses].sort(() => rand() - 0.5).slice(0, int(1, 4));
  for (const c of chosen) {
    const total = c.lessons.length;
    const full = rand() < 0.22;
    const doneCount = full ? total : int(0, total - 1);
    const pct = Math.round((doneCount / total) * 100);
    const startedDaysAgo = int(doneCount + 2, 40);
    emit(`INSERT INTO enrollments (user_id, course_id, status, progress_percent, enrolled_at, completed_at)
SELECT u.id, c.id, ${q(full ? 'completed' : 'active')}, ${pct}, ${ago(startedDaysAgo)}, ${full ? ago(int(0, 3), int(1, 20)) : 'NULL'} FROM users u, courses c WHERE u.email = ${q(mail)} AND c.slug = ${q(c.slug)}
ON CONFLICT (user_id, course_id) DO NOTHING;`);
    for (let k = 0; k < doneCount; k++) {
      const daysAgo = Math.max(0, Math.round(((doneCount - k) / doneCount) * Math.min(startedDaysAgo, 14)) - int(0, 1));
      emit(`INSERT INTO lesson_progress (user_id, lesson_id, completed, minutes_spent, quiz_score, completed_at)
SELECT u.id, l.id, TRUE, ${c.lessons[k][1] + int(-2, 6)}, ${pick([67, 100, 100, 33, 100, 67])}, ${ago(daysAgo, int(0, 12))} FROM users u, lessons l JOIN courses c ON c.id = l.course_id WHERE u.email = ${q(mail)} AND c.slug = ${q(c.slug)} AND l.order_index = ${k + 1}
ON CONFLICT (user_id, lesson_id) DO NOTHING;`);
    }
    if (full) {
      const code = `NOV-2026-${Array.from({ length: 6 }, () => certChars[int(0, certChars.length - 1)]).join('')}`;
      emit(`INSERT INTO certificates (user_id, course_id, certificate_code, issued_at)
SELECT u.id, c.id, ${q(code)}, ${ago(int(0, 3))} FROM users u, courses c WHERE u.email = ${q(mail)} AND c.slug = ${q(c.slug)}
ON CONFLICT DO NOTHING;`);
    }
  }
});

