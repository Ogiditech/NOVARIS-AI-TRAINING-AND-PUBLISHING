export const translations = { en };

export function translate(lang, path, vars = {}) {
  const pick = (dict) => path.split('.').reduce((o, k) => (o == null ? o : o[k]), dict);
  let value = pick(translations[lang]) ?? pick(translations.en) ?? path;
  // Count-based text: { one, other } chosen by vars.n (e.g. "1 day" vs "3 days").
  if (value && typeof value === 'object' && !Array.isArray(value) && 'other' in value) {
    value = Number(vars.n) === 1 ? value.one : value.other;
  }
  if (typeof value === 'string') {
    value = value.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  }
  return value;
}
